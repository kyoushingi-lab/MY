function readPreference(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch (_) { return fallback; }
}

function savePreference(key, value) {
  try { localStorage.setItem(key, value); } catch (_) { /* Storage may be unavailable. */ }
}

function translation(dict, key) {
  return key.split('.').reduce((node, part) => node && node[part], dict);
}

function currentLanguage() {
  const value = readPreference('lang', 'ja');
  return supportedLanguages.has(value) ? value : 'ja';
}

function localizedUrl(element, stem, lang) {
  const suffix = lang === 'ja' ? 'Ja' : lang === 'en' ? 'En' : 'Zh';
  return element.dataset[stem + suffix] || element.dataset[stem] || element.getAttribute('href') || '#';
}

function updateUiLabels(lang) {
  const labels = uiText[lang];
  const dark = document.getElementById('darkToggle');
  const menu = document.getElementById('menuToggle');
  dark.setAttribute('aria-label', document.documentElement.classList.contains('dark') ? labels.light : labels.dark);
  menu.setAttribute('aria-label', menu.getAttribute('aria-expanded') === 'true' ? labels.menuClose : labels.menuOpen);
  document.getElementById('backToTop').setAttribute('aria-label', labels.top);
  document.querySelector('iframe').setAttribute('title', labels.map);
}

function setLanguage(lang) {
  if (!supportedLanguages.has(lang)) lang = 'ja';
  const dict = i18n[lang];
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = translation(dict, element.dataset.i18n);
    if (typeof value === 'string') element.textContent = value.replace(/<br\s*\/?\s*>/gi, '\n');
  });
  document.querySelectorAll('.i18n-href').forEach(link => {
    link.href = localizedUrl(link, 'href', lang);
  });
  document.querySelectorAll('.lang-btn').forEach(button => {
    const active = button.dataset.lang === lang;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
  savePreference('lang', lang);
  updateUiLabels(lang);
}

function currentTabFromHash() {
  const match = /^#tab-(home|about|works|contact)$/.exec(location.hash);
  return match && tabIds.has(match[1]) ? match[1] : 'home';
}

